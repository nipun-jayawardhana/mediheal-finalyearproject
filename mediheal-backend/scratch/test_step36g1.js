runTest('TEST A — Sinhala urinary initial case ("මුත්රා කරනකොට වේදනාවක් තියෙනවා")', () => {
  const input = "මුත්රා කරනකොට වේදනාවක් තියෙනවා";

  const initialCase = clinicalCaseService.buildCanonicalClinicalCase({
    symptoms: [input],
  });

  const profile = clinicalCaseService.buildClinicalProfile(initialCase);
  console.log('Test A Initial Case:', JSON.stringify(initialCase, null, 2));
  console.log('Test A Profile:', JSON.stringify(profile, null, 2));

  assert(
    initialCase.positiveSymptoms.includes('painful urination'),
    `Must extract "painful urination" (got: ${JSON.stringify(initialCase.positiveSymptoms)})`
  );
  assert.strictEqual(profile.clinicalDomain, 'urinary', `Domain must be "urinary" (got: ${profile.clinicalDomain})`);

  // Simulate Turn 1 where patient answers a follow-up with no new positives (e.g. fever: "no")
  const turn1 = [
    {
      question: "Do you have a fever?",
      answer: "no",
      canonicalQuestion: "Do you have a fever?",
      canonicalAnswer: "no",
      clinicalConcept: "fever",
    },
  ];

  const caseAfterTurn1 = clinicalCaseService.buildCanonicalClinicalCase({
    symptoms: [input],
    conversation: turn1,
    positiveSymptoms: initialCase.positiveSymptoms,
    negativeFindings: initialCase.negativeFindings,
    context: initialCase.context,
    duration: initialCase.duration,
  });

  console.log('Test A After Turn 1:', JSON.stringify(caseAfterTurn1, null, 2));
  const profileAfterTurn1 = clinicalCaseService.buildClinicalProfile(caseAfterTurn1);

  assert(
    caseAfterTurn1.positiveSymptoms.includes('painful urination'),
    'Existing "painful urination" must remain intact after turn 1'
  );
  assert(
    caseAfterTurn1.negativeFindings.includes('no fever'),
    'Must include "no fever" after turn 1'
  );
  assert.strictEqual(profileAfterTurn1.clinicalDomain, 'urinary', 'Domain must remain "urinary" after turn 1');
});

