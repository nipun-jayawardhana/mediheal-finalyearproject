// TEST B — Sinhala blood-in-urine question + No
// -------------------------------------------------------------
runTest('TEST B — Sinhala blood-in-urine question + No ("නැත")', () => {
  const input = "මුත්රා කරනකොට වේදනාවක් තියෙනවා";

  // Question generated by Gemini in English, displayed in Sinhala
  const canonicalQ = "Have you noticed any blood in your urine?";
  const displayQ = "ඔබේ මුත්රා සමඟ රුධිරය පිටවීමක් ඔබ දුටුවාද?";
  const answer = "නැත";

  // Test question normalization
  const normalizedQ = geminiTranslationService.normalizeQuestionTextToEnglish(displayQ);
  console.log('Test B Normalized Q from Sinhala display:', normalizedQ);
  assert.strictEqual(
    normalizedQ,
    "Have you noticed any blood in your urine?",
    'Must normalize Sinhala blood in urine question to canonical English'
  );

  const turn = [
    {
      question: displayQ,
      answer: answer,
      canonicalQuestion: canonicalQ,
      canonicalAnswer: "no",
      clinicalConcept: "blood in urine",
    },
  ];

  const canonicalCase = clinicalCaseService.buildCanonicalClinicalCase({
    symptoms: [input],
    conversation: turn,
    positiveSymptoms: ['painful urination'],
  });

  console.log('Test B Result:', JSON.stringify(canonicalCase, null, 2));

  assert(
    canonicalCase.positiveSymptoms.includes('painful urination'),
    'Existing "painful urination" MUST remain positive'
  );
  assert(
    canonicalCase.negativeFindings.includes('no blood in urine'),
    `negativeFindings must include "no blood in urine" (got: ${JSON.stringify(canonicalCase.negativeFindings)})`
  );
});

