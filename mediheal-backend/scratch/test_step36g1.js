// TEST J — Neurological regression ("weakness in both feet for 1 week")
// -------------------------------------------------------------
runTest('TEST J — Neurological regression ("weakness in both feet for 1 week")', () => {
  const input = "weakness in both feet for 1 week";

  const case0 = clinicalCaseService.buildCanonicalClinicalCase({ symptoms: [input] });
  const prof0 = clinicalCaseService.buildClinicalProfile(case0);

  assert.strictEqual(prof0.clinicalDomain, 'neurology', 'Initial domain must be neurology');
  assert(case0.positiveSymptoms.some(s => s.includes('weakness')), 'Must extract weakness');
  assert(case0.context.some(c => c.includes('feet')), 'Must extract feet context');
  assert.strictEqual(case0.duration, '1 week', 'Duration must be 1 week');

  // Turn 1
  const turn1 = [{ question: "Have you noticed any numbness or tingling in your feet?", answer: "Yes", canonicalQuestion: "Have you noticed any numbness or tingling in your feet?", canonicalAnswer: "yes" }];
  const case1 = clinicalCaseService.buildCanonicalClinicalCase({ symptoms: [input], conversation: turn1, positiveSymptoms: case0.positiveSymptoms, context: case0.context, duration: case0.duration });

  // Turn 2
  const turn2 = [...turn1, { question: "Have you noticed any difficulty with your balance or walking?", answer: "No", canonicalQuestion: "Have you noticed any difficulty with your balance or walking?", canonicalAnswer: "no" }];
  const case2 = clinicalCaseService.buildCanonicalClinicalCase({ symptoms: [input], conversation: turn2, positiveSymptoms: case1.positiveSymptoms, context: case1.context, duration: case1.duration });

  // Turn 3
  const turn3 = [...turn2, { question: "Do you have any back pain?", answer: "No", canonicalQuestion: "Do you have any back pain?", canonicalAnswer: "no" }];
  const case3 = clinicalCaseService.buildCanonicalClinicalCase({ symptoms: [input], conversation: turn3, positiveSymptoms: case2.positiveSymptoms, context: case2.context, duration: case2.duration });

  console.log('Test J Final Case after 3 turns:', JSON.stringify(case3, null, 2));

  assert(case3.positiveSymptoms.some(s => s.includes('weakness')), 'Weakness must survive all turns');
  assert(case3.context.some(c => c.includes('feet')), 'Feet context must survive all turns');
  assert.strictEqual(case3.duration, '1 week', 'Duration must survive all turns');
  assert(case3.negativeFindings.includes('no balance or walking difficulty'), 'Must extract no balance or walking difficulty');
  assert(case3.negativeFindings.includes('no back pain'), 'Must extract no back pain');
});

